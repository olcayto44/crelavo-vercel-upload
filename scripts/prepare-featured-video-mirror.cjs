const LIMIT=12*1024*1024;
const dir=path.join(process.cwd(),"public/showcase/uploads");
const manifest=path.join(process.cwd(),"src/lib/featured-video-mirror.generated.ts");
async function download(item){
 const name="featured-"+item.id+".mp4",file=path.join(dir,name),temp=file+".part";
 try{
  const response=await fetch(item.url,{redirect:"error",signal:AbortSignal.timeout(12000)});
  if(!response.ok||!response.body)throw Error("HTTP "+response.status);
  if(Number(response.headers.get("content-length"))>LIMIT)throw Error("size limit");
  const chunks=[];let size=0;const reader=response.body.getReader();
  try{for(;;){const {done,value}=await reader.read();if(done)break;size+=value.byteLength;if(size>LIMIT)throw Error("size limit");chunks.push(Buffer.from(value));}}finally{await reader.cancel().catch(()=>{});}
  const bytes=Buffer.concat(chunks);
  if(bytes.length<1024||bytes.toString("ascii",4,8)!=="ftyp")throw Error("invalid MP4");
  await fs.writeFile(temp,bytes);
  // Decode a frame to reject corrupt files before replacing the original source.
  const ffmpeg=require("ffmpeg-static")||"ffmpeg";
  const check=require("node:child_process").spawnSync(ffmpeg,["-v","error","-i",temp,"-frames:v","1","-f","null","-"],{timeout:12000,stdio:"ignore"});
  if(check.status!==0)throw Error("decode failed");
  await fs.rename(temp,file);
  return [item.id,{source:item.url,local:"/showcase/uploads/"+name}];
 }catch(error){await fs.rm(temp,{force:true});console.warn("Original remote video retained:",item.id,error.message);return null}
}
